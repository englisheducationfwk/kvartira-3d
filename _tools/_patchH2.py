# --- диван складывается до конца: спинка ложится плоcко, петля ниже
rep("    backGrp.position.set(mx(3.39), 0.46, 1.95);",
    "    backGrp.position.set(mx(3.39), 0.44, 1.95);")
rep("                 dir:-sgn, rot0:-sgn*0.10, rot1: sgn*1.42, open:false, anim:null };",
    "                 dir:-sgn, rot0:-sgn*0.10, rot1: sgn*1.57, open:false, anim:null };")

p.write_text(s, encoding='utf-8')
print('H2 ok')
